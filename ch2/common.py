"""
Shared tools for the Chapter 2 re-derivation scripts.

Every script in ch2/ follows the same protocol:

  1. DERIVE   the object with SymPy (sp.solve / sp.diff / sp.limit), never by
              typing the final formula in;
  2. COMPARE  the derived object with the expression printed in the thesis
              (``claim``), and record PASS / FAIL;
  3. EXPORT   the derived closed forms as LaTeX to ch2/tex/<script>.tex and a
              plain-text log to ch2/results/<script>.txt.

A script exits with a non-zero status if any check fails.
"""

from __future__ import annotations

import random
import sys
from pathlib import Path

import sympy as sp

HERE = Path(__file__).resolve().parent
TEX_DIR = HERE / "tex"
RES_DIR = HERE / "results"
TEX_DIR.mkdir(exist_ok=True)
RES_DIR.mkdir(exist_ok=True)

# ---------------------------------------------------------------------------
# Common symbols (all strictly positive unless stated otherwise)
# ---------------------------------------------------------------------------
e, beta, n = sp.symbols("e beta n", positive=True)       # endowment, MPCR scale, group size
A, B = sp.symbols("A B", positive=True)                   # Cobb-Douglas exponents; B = prosocial weight
d = sp.symbols("d", positive=True)                        # closed-neighbourhood size
c, x = sp.symbols("c x", positive=True)                   # generic own contribution
Lam = sp.symbols("Lambda", positive=True)                 # generic impact multiplier
T = sp.symbols("T", nonnegative=True)                     # warm-glow baseline (comparison model)
sigma = sp.symbols("sigma", positive=True)                # elasticity of substitution
rho = sp.symbols("rho", real=True)                        # CES substitution parameter
delta = sp.symbols("delta", positive=True)                # CES weight on X

# Experimental parameterisation (Chapter 3)
EXP = {e: 15, n: 3, beta: sp.Rational(3, 2)}


# ---------------------------------------------------------------------------
# Check registry
# ---------------------------------------------------------------------------
class Log:
    def __init__(self, script: str):
        self.script = Path(script).stem
        self.lines: list[str] = []
        self.tex: list[str] = []
        self.n_pass = 0
        self.n_fail = 0

    # -- printing -----------------------------------------------------------
    def say(self, *msg):
        s = " ".join(str(m) for m in msg)
        print(s)
        self.lines.append(s)

    def head(self, title: str):
        bar = "=" * 78
        self.say("\n" + bar)
        self.say(title)
        self.say(bar)

    def show(self, label: str, expr):
        self.say(f"  {label} = {sp.sstr(expr)}")

    # -- checks -------------------------------------------------------------
    def check(self, label: str, ok: bool):
        ok = bool(ok)
        tag = "PASS" if ok else "FAIL"
        if ok:
            self.n_pass += 1
        else:
            self.n_fail += 1
        self.say(f"  [{tag}] {label}")
        return ok

    # -- LaTeX export -------------------------------------------------------
    def tex_eq(self, label: str, lhs: str, expr, note: str = ""):
        """Store `lhs = <latex(expr)>` as an equation for ch2/tex/<script>.tex."""
        body = sp.latex(expr)
        cmt = f"% {note}\n" if note else ""
        self.tex.append(
            f"{cmt}% derived: {label}\n\\begin{{equation*}}\n  {lhs} = {body}\n\\end{{equation*}}\n"
        )

    def finish(self):
        self.head(f"SUMMARY {self.script}: {self.n_pass} PASS, {self.n_fail} FAIL")
        (RES_DIR / f"{self.script}.txt").write_text("\n".join(self.lines) + "\n", encoding="utf-8")
        hdr = (
            f"% Auto-generated by ch2/{self.script}.py -- do not edit by hand.\n"
            f"% Closed forms below were DERIVED by SymPy, not typed in.\n\n"
        )
        (TEX_DIR / f"{self.script}.tex").write_text(hdr + "\n".join(self.tex), encoding="utf-8")
        if self.n_fail:
            sys.exit(1)


# ---------------------------------------------------------------------------
# Algebra helpers
# ---------------------------------------------------------------------------
def simp(expr):
    return sp.factor(sp.simplify(sp.together(expr)))


def same(a, b, sampler=None, trials: int = 25) -> bool:
    """True if a - b is identically zero: symbolic first, then exact rational
    evaluation at random admissible points (sampler returns a subs-dict)."""
    diff = sp.simplify(sp.together(a - b))
    if diff == 0:
        return True
    if sampler is None:
        return False
    for _ in range(trials):
        pt = sampler()
        val = sp.nsimplify(diff.subs(pt)) if not diff.subs(pt).is_number else diff.subs(pt)
        if abs(complex(sp.N(val, 30))) > 1e-20:
            return False
    return True


def rat(lo, hi, den: int = 997):
    """Random rational in the open interval (lo, hi)."""
    lo, hi = sp.nsimplify(lo), sp.nsimplify(hi)
    k = random.randint(1, den - 1)
    return lo + (hi - lo) * sp.Rational(k, den)


def positive_on(expr, sampler, trials: int = 400) -> bool:
    """Numerical sign check of expr > 0 on a sampled admissible region."""
    for _ in range(trials):
        pt = sampler()
        v = sp.N(expr.subs(pt), 30)
        if not (v.is_real and v > 0):
            return False
    return True


